// Package script hosts Surge-compatible HTTP scripts with replaceable execution engines.
package script

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"strings"
	"time"
	"unicode/utf8"
)

// Kind identifies the HTTP phase in which a script runs.
type Kind string

const (
	KindHTTPRequest  Kind = "http-request"
	KindHTTPResponse Kind = "http-response"
)

// Dialect identifies the platform whose $done semantics apply. The zero value
// uses Surge semantics.
type Dialect string

const (
	DialectSurge Dialect = "surge"
	DialectLoon  Dialect = "loon"
	DialectStash Dialect = "stash"
)

// HeaderField is one wire header field. Header lists retain order and duplicates.
type HeaderField struct{ Name, Value string }

// Script is the source and options for one HTTP script.
type Script struct {
	Key        string // Cache key. An empty key uses the source hash.
	Name       string
	Path       string // Scripts with the same path share their default storage key.
	Source     string
	Kind       Kind
	Dialect    Dialect
	Engine     string // Host engine selection hint.
	BinaryBody bool
	FullHeader bool
	Argument   *string       // nil leaves $argument undefined.
	Timeout    time.Duration // Nonpositive values use DefaultTimeout.
	MaxSize    int64         // Nonpositive values use only the host's hard limit.
}

// CacheKey returns the explicit key or the SHA-256 hash of the source.
func (s *Script) CacheKey() string {
	if s.Key != "" {
		return s.Key
	}
	sum := sha256.Sum256([]byte(s.Source))
	return hex.EncodeToString(sum[:])
}

// Request is the request visible to an HTTP script.
type Request struct {
	ID      string // Shared by the request and response scripts for one request.
	Method  string
	URL     string
	Headers []HeaderField
	Body    []byte // nil means there is no body to expose.
}

// Response is an input response or a response generated by a request script.
type Response struct {
	Status  int
	Headers []HeaderField
	Body    []byte
}

// Input contains the HTTP messages for one script session.
type Input struct {
	Request  Request
	Response *Response // Required for http-response scripts.
}

// Engine runs script sessions. Run and Purge may be called concurrently.
type Engine interface {
	// Run reports the first $done call without interpreting it. A session ends
	// at that call, an uncaught exception, quiescence, or context termination.
	// Report a timed-out run as ErrTimeout and a canceled run as ctx.Err().
	Run(ctx context.Context, job *Job) (Done, error)
	// Purge discards rebuildable state, such as compiled programs.
	Purge()
}

// Job carries the input, services, and effective limits for an engine run.
type Job struct {
	Script   *Script
	Input    *Input
	Env      Environment
	Services Services
	Limits   Limits
}

// Done represents the first $done argument independently of dialect and phase.
type Done struct {
	Called     bool
	HasValue   bool // The argument is neither undefined nor null.
	URL        *string
	Status     *int // The status or statusCode field.
	Headers    []HeaderField
	HeadersSet bool
	Body       []byte
	BodySet    bool
	Response   *Response
	Abort      bool
}

// Action describes how a script result applies to its HTTP exchange.
type Action int

const (
	ActionPass Action = iota
	ActionModify
	ActionRespond
	ActionAbort
)

// Result is the host's interpretation of a $done argument. Set flags
// distinguish omission from an explicit empty header list or body.
type Result struct {
	Action     Action
	URL        *string
	Status     int // Zero leaves the response status unchanged.
	Headers    []HeaderField
	HeadersSet bool
	Body       []byte
	BodySet    bool
	Response   *Response
	Duration   time.Duration // Time spent in the engine.
}

var (
	ErrTimeout        = errors.New("script timed out")
	ErrNoDone         = errors.New("script ended without calling $done")
	ErrBodyTooLarge   = errors.New("script input body exceeds the size limit")
	ErrCircuitOpen    = errors.New("script circuit breaker is open")
	ErrBusy           = errors.New("script concurrency slot unavailable before deadline or cancellation")
	ErrLowMemory      = errors.New("script skipped due to insufficient memory headroom")
	ErrMemoryExceeded = errors.New("script result discarded because memory exceeded the budget")
)

// ScriptError contains the first line of a script's exception or syntax error.
type ScriptError struct {
	Name    string
	Message string
}

// NewScriptError keeps a bounded copy of the first line of message.
func NewScriptError(name, message string) *ScriptError {
	const maxBytes = 1024
	if len(message) > maxBytes {
		end := maxBytes
		for end > 0 && !utf8.RuneStart(message[end]) {
			end--
		}
		message = message[:end]
	}
	if i := strings.IndexAny(message, "\r\n\u2028\u2029"); i >= 0 {
		message = message[:i]
	}
	return &ScriptError{Name: name, Message: strings.Clone(message)}
}

func (e *ScriptError) Error() string {
	if e.Name == "" {
		return "script: " + e.Message
	}
	return fmt.Sprintf("script %q: %s", e.Name, e.Message)
}
