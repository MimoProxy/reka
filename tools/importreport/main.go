// importreport emits credential-free compatibility tables and import coverage
// for local subscription files.
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/MimoProxy/reka/internal/config/importer"
)

func main() {
	support := flag.Bool("support", false, "print the current field support matrix")
	flag.Parse()
	if *support {
		fmt.Println("# Clash import support\n\nReference behavior: [mihomo v1.19.34](https://github.com/MetaCubeX/mihomo/tree/v1.19.34), especially [proxy parsing](https://github.com/MetaCubeX/mihomo/blob/v1.19.34/adapter/parser.go), [VLESS defaults](https://github.com/MetaCubeX/mihomo/blob/v1.19.34/adapter/outbound/vless.go) and [group parsing](https://github.com/MetaCubeX/mihomo/blob/v1.19.34/adapter/outboundgroup/parser.go). This table describes conversion to the current runtime subset.\n\nGenerated by `go run ./tools/importreport -support`. Unlisted fields inside imported resources make the resource unavailable. Unsupported content blocks application by default; explicit nodes-only or partial mode must be reviewed. See [import usage](clash-import.md).\n\n| Scope | Field | Status | Behavior |\n| --- | --- | --- | --- |")
		for _, e := range importer.SupportMatrix() {
			fmt.Printf("| %s | `%s` | %s | %s |\n", e.Scope, e.Field, e.Status, strings.ReplaceAll(e.Notes, "|", "\\|"))
		}
		return
	}
	if flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "usage: importreport [-support] FILE...")
		os.Exit(2)
	}
	fmt.Println("# Import coverage\n\nInputs are numbered in command-line order. This is conversion coverage, not live connectivity.\n\nGenerated by `go run ./tools/importreport FILE...`. Counts below use explicit partial mode to measure supported resources; default application of incomplete content remains blocked.\n\n| Input | Nodes | Groups | Rules | Partial | Can apply partial | Nodes-only can apply |\n| --- | --- | --- | --- | --- | --- | --- |")
	codes := map[string]int{}
	for i, path := range flag.Args() {
		data, err := os.ReadFile(path)
		if err != nil {
			fmt.Fprintln(os.Stderr, "read input failed")
			os.Exit(1)
		}
		req := importer.Request{SourceID: fmt.Sprintf("input-%d", i+1), Data: string(data), AllowPartial: true}
		r := importer.Import(req).Report
		req.AllowPartial = false
		req.NodesOnly = true
		only := importer.Import(req).Report
		fmt.Printf("| %d | %d/%d | %d/%d | %d/%d | %t | %t | %t |\n", i+1, r.Nodes.Imported, r.Nodes.Total, r.Groups.Imported, r.Groups.Total, r.Rules.Imported, r.Rules.Total, r.Partial, r.CanApply, only.CanApply)
		for _, d := range r.Diagnostics {
			codes[d.Code]++
		}
	}
	fmt.Println("\nDiagnostics (counts, no input values):\n\n| Code | Count |\n| --- | --- |")
	keys := []string{}
	for code := range codes {
		keys = append(keys, code)
	}
	sort.Strings(keys)
	for _, code := range keys {
		fmt.Printf("| `%s` | %d |\n", code, codes[code])
	}
}
